// Generates src/content/logos.ts from the Simple Icons set (a dev dependency).
// Only the listed icons are written, so nothing from the icon package ships at runtime.
//   npm run logos
import * as si from "simple-icons";
import { writeFileSync } from "node:fs";

// [simple-icons export, display name, group]. Every entry is a technology actually used in a project.
const list = [
  ["siPython", "Python", "Languages"],
  ["siTypescript", "TypeScript", "Languages"],
  ["siJavascript", "JavaScript", "Languages"],
  ["siHtml5", "HTML5", "Languages"],
  ["siFastapi", "FastAPI", "Back end and data"],
  ["siFlask", "Flask", "Back end and data"],
  ["siNodedotjs", "Node.js", "Back end and data"],
  ["siExpress", "Express", "Back end and data"],
  ["siSqlalchemy", "SQLAlchemy", "Back end and data"],
  ["siPydantic", "Pydantic", "Back end and data"],
  ["siPostgresql", "PostgreSQL", "Back end and data"],
  ["siSqlite", "SQLite", "Back end and data"],
  ["siMongodb", "MongoDB", "Back end and data"],
  ["siSupabase", "Supabase", "Back end and data"],
  ["siScikitlearn", "scikit-learn", "Applied ML and AI"],
  ["siPytorch", "PyTorch", "Applied ML and AI"],
  ["siNumpy", "NumPy", "Applied ML and AI"],
  ["siOpencv", "OpenCV", "Applied ML and AI"],
  ["siGooglegemini", "Gemini API", "Applied ML and AI"],
  ["siClaude", "Claude API", "Applied ML and AI"],
  ["siReact", "React", "Interfaces"],
  ["siNextdotjs", "Next.js", "Interfaces"],
  ["siVite", "Vite", "Interfaces"],
  ["siTailwindcss", "Tailwind CSS", "Interfaces"],
  ["siThreedotjs", "three.js", "Interfaces"],
  ["siMaplibre", "MapLibre", "Interfaces"],
  ["siGreensock", "GSAP", "Interfaces"],
  ["siDocker", "Docker", "Tooling"],
  ["siPytest", "pytest", "Tooling"],
  ["siGit", "Git", "Tooling"],
];

const rows = list.map(([key, name, group]) => {
  const icon = si[key];
  if (!icon) throw new Error(`missing icon export ${key}`);
  return `  { id: ${JSON.stringify(icon.slug)}, name: ${JSON.stringify(name)}, group: ${JSON.stringify(group)}, hex: ${JSON.stringify(icon.hex)}, path: ${JSON.stringify(icon.path)} },`;
});

const out = `// GENERATED by scripts/make-logos.mjs from Simple Icons (CC0). Do not edit by hand.
export type Logo = { id: string; name: string; group: string; hex: string; path: string };

export const logos: Logo[] = [
${rows.join("\n")}
];

export const logoGroups = ${JSON.stringify([...new Set(list.map((l) => l[2]))])} as const;
`;
writeFileSync("src/content/logos.ts", out);
console.log(`wrote ${list.length} logos`);
